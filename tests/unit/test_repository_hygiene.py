"""Repository hygiene: no tracked file holds a personal home path or a global IP address, and local pointer files stay
untracked."""
import ipaddress
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]

# Every pattern and synthetic value is built from fragments, so this file never matches itself.
ROOTS = ('ho' + 'me', 'Us' + 'ers')
HOME_PATH = re.compile(rb'(?<![A-Za-z0-9._-])/(?:' + b'|'.join(r.encode() for r in ROOTS) + rb')/[A-Za-z0-9._-]+/')
LOCAL_POINTERS = ('CLAUDE.local.md', '.agents/rules/90-local.md')


def home_path_hits(name, data):
    """Offsets of home paths in data."""
    return [m.start() for m in HOME_PATH.finditer(data)]


def home_path_failures(items):
    """items: (repository-relative name, bytes) pairs; returns the failures as text."""
    failures = []
    for name, data in items:
        hits = home_path_hits(name, data)
        if hits:
            failures.append(f'{name}:{len(hits)}')
    return failures


def tracked_files():
    # No skip: without git the guard cannot run, and that is a failure.
    out = subprocess.run(['git', '-C', str(ROOT), 'ls-files', '-z'], check=True, capture_output=True).stdout
    return [name for name in out.decode('utf-8').split('\0') if name]


def _home(rest):
    return b'/' + ROOTS[0].encode() + rest


def test_scanner_detects_home_and_users_paths():
    assert len(home_path_hits('notes.md', b'x ' + _home(b'/someone/y'))) == 1
    assert len(home_path_hits('notes.md', b'x /' + ROOTS[1].encode() + b'/someone/y')) == 1
    assert home_path_failures([('notes.md', b'x ' + _home(b'/someone/y') + b' ' + _home(b'/other/z'))]) == ['notes.md:2']


def test_scanner_ignores_word_list_fragment():
    # A slash-separated word list such as 'clone/gold/<home>/temp/antenati' is not a home path.
    data = b'| CLA-I005 | Allowlist; clone/gold/' + ROOTS[0].encode() + b'/temp/antenati scratch rejected. |\n'
    assert home_path_hits('notes.md', data) == []


def test_tracked_files_have_no_home_paths():
    items = []
    for name in tracked_files():
        path = ROOT / name
        if path.is_file() and not path.is_symlink():
            items.append((name, path.read_bytes()))
    assert items
    assert home_path_failures(items) == []


# Global IP addresses (MFL023 B10): an address of a real client (in a log copied into a fixture, say) has no place in a
# public repository. The documentation ranges (RFC 5737: 192.0.2.0/24, 198.51.100.0/24, 203.0.113.0/24; RFC 3849:
# 2001:db8::/32) are for examples. Text files only (no NUL byte, valid UTF-8: the binary renders of the corpus are not
# text). An IPv6 candidate with two colons is a compressed address (one `::`, built from fragments in the tests) unless
# it stands in a subscript, as a slice of Python does (`data[0::2]`, `held[-1][::4096]`, `a[:, ::2]`): the last `[`
# before it on its line, not yet closed, follows a name, `)`, `]` or a quote (MFL023 B11, SOL-B10-N1). A slice has two
# colons at most, so the candidates with three or more are always checked. `uv.lock` is generated by uv from the
# package index (names, versions such as those of the CUDA wheels, hashes and URLs of the index): it holds no address
# of a client and is not scanned. Dotted numbers of the other files that parse as addresses but are versions are listed
# with their origin; a new one is added here with its own. A failure names the file and the count, never the address.
DOCUMENTATION = tuple(ipaddress.ip_network(n) for n in ('192.0.2.0/24', '198.51.100.0/24', '203.0.113.0/24',
                                                        '2001:db8::/32'))
GENERATED = ('uv.lock',)
VERSIONS = {'.'.join(('26', '8', '3', '1')): 'LibreOffice of the engine toolchain (toolchain.json, Dockerfile, bench.md)'}
IPV4 = re.compile(rb'(?<![0-9A-Za-z.])(\d{1,3}(?:\.\d{1,3}){3})(?![0-9A-Za-z]|\.\d)')
IPV6 = re.compile(rb'(?<![0-9A-Za-z:.])((?:[0-9A-Fa-f]{0,4}:){2,7}[0-9A-Fa-f]{0,4})(?![0-9A-Za-z:])')
SUBSCRIPT = re.compile(rb'[0-9A-Za-z_)\]\'"]\[[^\[\]\n]*$')


def in_subscript(data, start):
    """True when the text at `start` stands in a subscript: the last `[` before it on its line, not yet closed, follows
    a name, `)`, `]` or a quote."""
    return SUBSCRIPT.search(data[data.rfind(b'\n', 0, start) + 1:start]) is not None


def global_address_hits(data):
    """The number of global addresses outside the documentation ranges in `data` (bytes of a text file)."""
    hits = 0
    for rx in (IPV4, IPV6):
        for m in rx.finditer(data):
            text = m.group(1).decode('ascii')
            if text in VERSIONS or rx is IPV6 and text.count(':') == 2 and in_subscript(data, m.start(1)):
                continue
            try:
                address = ipaddress.ip_address(text)
            except ValueError:
                continue
            if address.is_global and not any(address in net for net in DOCUMENTATION if net.version == address.version):
                hits += 1
    return hits


def global_address_failures(items):
    failures = []
    for name, data in items:
        if name in GENERATED or b'\0' in data:
            continue
        try:
            data.decode('utf-8')
        except UnicodeDecodeError:
            continue
        hits = global_address_hits(data)
        if hits:
            failures.append(f'{name}:{hits}')
    return failures


def test_scanner_detects_global_addresses_only():
    synthetic_v4 = '.'.join(('8', '8', '4', '4')).encode()                       # public resolvers, not a client
    synthetic_v6 = ':'.join(('2606', '4700', '4700', '', '1111')).encode()
    assert global_address_failures([('log.txt', b'client ' + synthetic_v4 + b':0 - "POST /v1/chat/completions"')]) \
        == ['log.txt:1']
    assert global_address_failures([('log.txt', b'from ' + synthetic_v6 + b' and ' + synthetic_v4)]) == ['log.txt:2']
    documentation = b'203.0.113.7 198.51.100.20 192.0.2.1 2001:db8::1 2001:db8:0:1::5'
    private = b'127.0.0.1 10.1.2.3 192.168.1.10 172.16.0.1 ::1 fe80::1:2:3 169.254.0.1 0.0.0.0'
    versions = b'soffice ' + '.'.join(('26', '8', '3', '1')).encode() + b'; data[0::2], held[::4096], 10:29:10'
    assert global_address_failures([('a.txt', documentation + b'\n' + private + b'\n' + versions)]) == []
    assert global_address_failures([('page.png', b'\x89PNG\0' + synthetic_v4)]) == []


def test_scanner_detects_compressed_ipv6():
    """MFL023 B11 (SOL-B10-N1): a global address with one `::` and two colons, short or long, in the forms of a log."""
    short = ':'.join(('2606', '', '1111')).encode()                              # public resolvers, not a client
    other = ':'.join(('2a00', '', '1')).encode()
    long = ':'.join(('2606', '4700', '4700', '', '1111')).encode()
    for line in (b'client ' + short + b' - "POST /v1/chat/completions"', b'from ' + short + b',',
                 b'GET http://[' + short + b']:443/health', b'peer [' + short + b']:443 closed', b'(' + short + b')',
                 b'"ip": "' + short + b'"', b'addr=' + short + b'\n', short, b'x[0] ' + short):
        assert global_address_hits(line) == 1, line
    both = b'from ' + short + b' and ' + other + b' and ' + long
    assert global_address_failures([('log.txt', both)]) == ['log.txt:3']
    documentation = ':'.join(('2001', 'db8', '', '1')).encode()
    assert global_address_hits(documentation + b' ::1 fe80::1 fc00::5 fe80::1:2:3') == 0


def test_scanner_ignores_slices_and_other_forms():
    """The forms with `::` that are not addresses: slices of Python in a subscript (one or more dimensions, after a
    name, a call, a subscript or a string), names of a namespace, times, the unspecified address."""
    slices = (b'pairs = dict(zip(attrs[0::2], attrs[1::2]))', b'n = len(held[-1][::4096])', b'self.rebuild()[::2]',
              b'img[:, ::2]', b"'abcd'[::2]", b'x[1::]', b'rows[i][1::3]', b'`data[0::2]` is a slice of Python')
    others = (b'std::vector', b'Foo::Bar', b'module::function', b'10:29:10', b'12:00:00.5', b'::', b'f :: Int -> Int',
              b'1:2:3')
    for line in slices + others:
        assert global_address_hits(line) == 0, line


def test_tracked_files_have_no_global_addresses():
    items = []
    for name in tracked_files():
        path = ROOT / name
        if path.is_file() and not path.is_symlink():
            items.append((name, path.read_bytes()))
    assert items
    assert global_address_failures(items) == []


def test_local_pointer_files_are_not_tracked():
    tracked = set(tracked_files())
    assert not tracked & set(LOCAL_POINTERS)
